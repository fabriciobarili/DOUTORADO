class TripParquetSink:
    """Sink Parquet com **RAM estável**.

    Mudança crítica: não usamos mais `list[dict]` (muito caro em Python e explode RAM).
    Em vez disso, mantemos buffers **colunares** (listas por coluna) e geramos Arrow Table no flush.
    """
    def __init__(self, out_dir: str, flush_rows: int = 25_000):
        self.out_dir = out_dir
        os.makedirs(out_dir, exist_ok=True)
        self.flush_rows = int(flush_rows)

        # buffers colunares na ordem do schema
        self._col_names = [f.name for f in TRIP_SCHEMA]
        self.cols = {name: [] for name in self._col_names}

        self.part = 0

    def add(self, row: dict):
        # append por coluna (bem mais leve do que dict por linha)
        for name in self._col_names:
            self.cols[name].append(row[name])

        # flush por tamanho de qualquer coluna (todas têm mesmo tamanho)
        if len(self.cols[self._col_names[0]]) >= self.flush_rows:
            self.flush()

    def flush(self):
        n = len(self.cols[self._col_names[0]])
        if n == 0:
            return

        # Constrói Table sem inferência (schema fixo)
        table = pa.table(self.cols, schema=TRIP_SCHEMA)
        path = f"{self.out_dir}/part-{self.part:05d}.parquet"
        pq.write_table(table, path, compression="zstd", use_dictionary=True, write_statistics=True)

        self.part += 1

        # limpa buffers
        for name in self._col_names:
            self.cols[name].clear()

    def flush_all(self):
        self.flush()

    def flush_day(self, date_str: str):
      """
      Flush + close apenas das partições referentes a date_str.
      Isso evita crescimento de RAM ao longo dos dias.
      """
      # Coleta chaves que pertencem ao dia
      to_flush = []
      for key in list(self._writers.keys()):
          # key pode ser string com path ou tupla com date_str na posição 0
          if isinstance(key, str):
              if f"date={date_str}" in key or key.startswith(date_str) or (date_str in key):
                  to_flush.append(key)
          else:
              # tupla/list: tente achar date_str em qualquer item
              if any((isinstance(x, str) and x == date_str) or (isinstance(x, str) and f"date={date_str}" in x) for x in key):
                  to_flush.append(key)

      # Flush/close e remove do dicionário (libera memória!)
      for key in to_flush:
          w = self._writers.pop(key, None)
          if w is None:
              continue

          # Seu writer pode ter flush()/close() ou flush_all()
          if hasattr(w, "flush"):
              w.flush()
          if hasattr(w, "close"):
              w.close()
          elif hasattr(w, "flush_all"):
              w.flush_all()

