"""### Análise de Atrasos dos Voos para SBPA

Nesta etapa, vamos identificar os voos atrasados e o grau de severidade do atraso.

**Metodologia:**
1. **Conversão de Tipos:** Primeiro, garantimos que as colunas `CHEGADA_PREVISTA` e `CHEGADA_REAL` sejam interpretadas como datas e horas (formato *datetime*).
2. **Cálculo do Atraso:** Subtraímos a previsão da chegada real para obter a diferença em minutos.
3. **Definição de Limites (Thresholds):** Na aviação comercial (padrão de agências como a FAA e ANAC), um voo é geralmente considerado "No Prazo" se chegar em até 14 minutos e 59 segundos após o horário estipulado. Com base nisso, classificamos os voos nas seguintes categorias:
   * **No Prazo:** Chegou antes da hora ou com menos de 15 minutos de atraso.
   * **Atraso Leve:** Atraso entre 15 e 59 minutos.
   * **Atraso Moderado:** Atraso entre 1 hora (60 min) e 2 horas (119 min).
   * **Atraso Grave:** Atraso de 2 horas (120 min) ou mais.
   * **Desconhecido / Cancelado:** Voos sem registro de horário de chegada real.
"""

import numpy as np

# 1. Converter as colunas de data/hora para o formato datetime do pandas
# Usamos errors='coerce' para transformar valores inválidos (ou vazios) em NaT (Not a Time)
df_voos_sbpa['CHEGADA_PREVISTA'] = pd.to_datetime(df_voos_sbpa['CHEGADA_PREVISTA'], errors='coerce')
df_voos_sbpa['CHEGADA_REAL'] = pd.to_datetime(df_voos_sbpa['CHEGADA_REAL'], errors='coerce')

# 2. Calcular o tempo de atraso em minutos
# Se o resultado for negativo, significa que o voo chegou adiantado.
df_voos_sbpa['ATRASO_MINUTOS'] = (df_voos_sbpa['CHEGADA_REAL'] - df_voos_sbpa['CHEGADA_PREVISTA']).dt.total_seconds() / 60

# 3. Criar a regra de classificação do grau de atraso usando numpy.select
condicoes = [
    (df_voos_sbpa['ATRASO_MINUTOS'].isna()),                            # Sem horário registrado
    (df_voos_sbpa['ATRASO_MINUTOS'] < 15),                              # Chegou adiantado ou com menos de 15 min de atraso
    (df_voos_sbpa['ATRASO_MINUTOS'] >= 15) & (df_voos_sbpa['ATRASO_MINUTOS'] < 60),  # 15 a 59 min
    (df_voos_sbpa['ATRASO_MINUTOS'] >= 60) & (df_voos_sbpa['ATRASO_MINUTOS'] < 120), # 1 a 2 horas
    (df_voos_sbpa['ATRASO_MINUTOS'] >= 120)                             # 2 horas ou mais
]

# Rótulos para cada condição acima, na mesma ordem
categorias = [
    'Desconhecido / Cancelado',
    'No Prazo (< 15 min)',
    'Atraso Leve (15-59 min)',
    'Atraso Moderado (1-2 h)',
    'Atraso Grave (> 2 h)'
]

# Criar a nova coluna aplicando as condições
df_voos_sbpa['STATUS_ATRASO'] = np.select(condicoes, categorias, default='Outro')

# --- Exibição Explicativa dos Resultados ---

