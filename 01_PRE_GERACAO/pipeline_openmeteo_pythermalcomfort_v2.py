def weather_code_instability_score(code):
    """Transforma código WMO em pontuação de instabilidade climática."""
    if pd.isna(code):
        return 0
    code = int(code)

    if code in {95, 96, 99}:      # trovoadas
        return 90
    if code in {65, 75, 82, 86}:  # precipitação forte
        return 75
    if code in {63, 73, 81, 85}:  # precipitação moderada
        return 55
    if code in {45, 48, 51, 53, 55, 56, 57, 61, 66, 67, 71, 77, 80}:
        return 35
    if code in {3}:               # encoberto
        return 10
    return 0


