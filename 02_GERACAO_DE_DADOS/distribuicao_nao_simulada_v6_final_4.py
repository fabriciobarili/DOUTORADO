class _AliasSampler:
    __slots__ = ("items","prob","alias","n")
    def __init__(self, items, weights):
        self.items = items
        n = len(items)
        self.n = n
        if n == 0:
            self.prob, self.alias = [], []
            return
        w = np.array(weights, dtype=np.float64)
        s = w.sum()
        if s <= 0:
            self.prob = [1.0]*n
            self.alias= list(range(n))
            return
        w = w * n / s
        small, large = [], []
        prob = np.zeros(n, dtype=np.float64)
        alias = np.zeros(n, dtype=np.int32)
        for i, wi in enumerate(w):
            if wi < 1.0: small.append(i)
            else: large.append(i)
        while small and large:
            s_i = small.pop()
            l_i = large.pop()
            prob[s_i] = w[s_i]
            alias[s_i] = l_i
            w[l_i] = (w[l_i] + w[s_i]) - 1.0
            if w[l_i] < 1.0: small.append(l_i)
            else: large.append(l_i)
        for i in large + small:
            prob[i] = 1.0
            alias[i] = i
        self.prob = prob.tolist()
        self.alias = alias.tolist()

    def sample(self):
        if self.n == 0:
            return None
        i = random.randrange(self.n)
        if random.random() < self.prob[i]:
            return self.items[i]
        return self.items[self.alias[i]]

class DemandModel:
    def __init__(self, valid_h3s, events):
        self.valid_h3s = valid_h3s
        self.M = len(valid_h3s)
        self.events_by_hour = defaultdict(list)
        for ev in events:
            t = _floor_to_hour(ev.start)
            end_h = _floor_to_hour(ev.end)
            while t <= end_h:
                self.events_by_hour[(ev.apply_to, t)].append(ev)
                #t += timedelta(hours=1)
                t += 3600 * 1000
        self.cache = {}

    def _build_bucket(self, apply_to: str, bucket: datetime):
        active = self.events_by_hour.get((apply_to, bucket), [])
        if not active:
            self.cache[(apply_to, bucket)] = (0.0, None, None, None)
            return
        extra = defaultdict(float)
        best  = {}
        for ev in active:
            w = ev.weight
            for cell in ev.affected_h3s:
                extra[cell] += w
                prev = best.get(cell)
                if prev is None or w > prev[1]:
                    best[cell] = (ev.name, w)
        affected_cells = list(extra.keys())
        affected_weights = [extra[c] for c in affected_cells]
        S = float(sum(affected_weights))
        sampler = _AliasSampler(affected_cells, affected_weights) if S > 0 else None
        self.cache[(apply_to, bucket)] = (S, sampler, best, dict(extra))

    def choose_h3(self, t: datetime, apply_to: str):
        bucket = _floor_to_hour(t)
        key = (apply_to, bucket)
        if key not in self.cache:
            self._build_bucket(apply_to, bucket)
        S, sampler, best, _extra = self.cache[key]
        if S <= 0 or sampler is None:
            cell = random.choice(self.valid_h3s)
            return cell, None
        if random.random() < (self.M / (self.M + S)):
            cell = random.choice(self.valid_h3s)
            return cell, None
        else:
            cell = sampler.sample()
            ev_name = best.get(cell, (None, 0.0))[0]
            return cell, ev_name

    def local_weights(self, t: datetime, apply_to: str):
        bucket = _floor_to_hour(t)
        key = (apply_to, bucket)
        if key not in self.cache:
            self._build_bucket(apply_to, bucket)
        _S, _sampler, best, extra = self.cache[key]
        return (best or {}), (extra or {})

