HOUR_MS = 3600 * 1000

def _floor_to_hour(dt_or_ms):
    if isinstance(dt_or_ms, (int, float)):
        return (int(dt_or_ms) // HOUR_MS) * HOUR_MS
    return int(dt_or_ms.replace(minute=0, second=0, microsecond=0).timestamp() * 1000)

class TimeModel:
    @staticmethod
    def travel_time_minutes(h3_dist: int) -> float:
        distance_km = max(0.0, float(h3_dist)) * float(KM_PER_H3_CELL)
        speed = max(10.0, random.normalvariate(AVG_SPEED_KMH, 4))
        return (distance_km / speed) * 60.0

    @staticmethod
    def idle_time_minutes(weekday: int) -> float:
        base = float(np.random.exponential(IDLE_MEAN_MINUTES))
        base = min(base, float(IDLE_MAX_MINUTES))  # truncagem: evita idles gigantes
        factor = WORK_PROBABILITY[weekday]
        # dias de mais demanda => menos idle
        return max(1.0, base * (1.05 - 0.55 * factor))

def call_probability(h3_distance: int) -> float:
    if h3_distance <= 0:
        return 1.0
    x = h3_distance / float(CALL_MAX_DIST)
    if x <= 1.0:
        p = float(CALL_BASE_P) * (1.0 - x * x)
        return max(float(CALL_FLOOR_P), p)
    # fora do raio: cai, mas não zera
    return max(0.02, float(CALL_FLOOR_P) / (1.0 + (x - 1.0) * 2.5))

