def _result_attr(result, attr_name):
    """Extrai atributo de dataclass, dict ou objeto indexável retornado pelo pythermalcomfort."""
    if hasattr(result, attr_name):
        return getattr(result, attr_name)
    if isinstance(result, dict):
        return result.get(attr_name)
    try:
        return result[attr_name]
    except Exception:
        raise AttributeError(f"Não foi possível extrair '{attr_name}' do resultado: {result}")


def _as_1d_array(value, n_expected: int):
    """Converte saída escalar/lista/array em vetor 1D com tamanho esperado."""
    arr = np.asarray(value)
    if arr.shape == ():
        return np.repeat(arr, n_expected)
    return arr.reshape(-1)


def run_pythermal_model(func, attrs, valid_mask, **kwargs):
    """
    Executa um modelo vetorizado do pythermalcomfort somente nas linhas válidas.

    Retorna um dicionário {atributo: array}, preservando NaN nas linhas inválidas.
    """
    n = len(valid_mask)
    idx = np.where(valid_mask)[0]

    output = {attr: np.full(n, np.nan, dtype=object) for attr in attrs}
    if len(idx) == 0:
        return output

    sliced_kwargs = {}
    for key, value in kwargs.items():
        if isinstance(value, (pd.Series, np.ndarray, list, tuple)) and len(value) == n:
            sliced_kwargs[key] = np.asarray(value)[idx]
        else:
            sliced_kwargs[key] = value

    try:
        result = func(**sliced_kwargs)
    except Exception as exc:
        print(f"Falha ao executar {getattr(func, '__name__', str(func))}: {exc}")
        return output

    for attr in attrs:
        values = _as_1d_array(_result_attr(result, attr), len(idx))
        output[attr][idx] = values

    return output

