EXCEL_EPOCH = datetime(1899, 12, 30)


def resolve_input_path(config: dict) -> Path:
    """Encontra o arquivo de entrada no Colab ou no ambiente local."""
    candidates = [Path(config["input_path"]), Path(config["fallback_input_path"])]
    for path in candidates:
        if path.exists():
            return path
    raise FileNotFoundError(
        "Arquivo não encontrado. Ajuste CONFIG['input_path'] para o caminho correto."
    )


def date_decimal_to_float(dt: datetime | date) -> float:
    """
    Recupera decimal convertido indevidamente em data pelo Excel.

    Exemplos:
    - 22 de setembro -> 22.9
    - 2 de julho -> 2.7
    - 14 de janeiro -> 14.1

    Para meses 10, 11 e 12, usa month/100, pois nesses casos o valor original
    provavelmente tinha duas casas decimais ou ocorreu ambiguidade de localidade.
    """
    day = float(dt.day)
    month = float(dt.month)
    if 1 <= month <= 9:
        return day + month / 10.0
    return day + month / 100.0


def excel_serial_to_datetime(value: float) -> datetime:
    """Converte número serial do Excel em datetime."""
    return EXCEL_EPOCH + timedelta(days=float(value))


def excel_date_decimal_to_float(value):
    """
    Corrige valores meteorológicos convertidos para data pelo Excel.

    A sua planilha contém células formatadas como d.m. Assim, um valor como 22.9
    pode aparecer internamente como uma data, e precisa ser recuperado como float.
    """
    if pd.isna(value):
        return np.nan

    if isinstance(value, pd.Timestamp):
        value = value.to_pydatetime()

    if isinstance(value, datetime) or isinstance(value, date):
        return date_decimal_to_float(value)

    if isinstance(value, str):
        text = value.strip().replace(",", ".")

        # Caso a data tenha vindo como texto dentro de uma coluna numérica.
        if re.match(r"^\d{4}-\d{2}-\d{2}", text):
            parsed = pd.to_datetime(text, errors="coerce")
            if not pd.isna(parsed):
                return excel_date_decimal_to_float(parsed)

        return pd.to_numeric(text, errors="coerce")

    # Caso raro: pandas pode devolver o serial numérico do Excel em vez de Timestamp.
    numeric = pd.to_numeric(value, errors="coerce")
    if pd.isna(numeric):
        return np.nan
    if 35000 <= float(numeric) <= 60000:
        return date_decimal_to_float(excel_serial_to_datetime(float(numeric)))
    return float(numeric)


def clean_numeric_weather_column(series: pd.Series) -> pd.Series:
    """Aplica correção de datas indevidas e converte a coluna para float."""
    return series.map(excel_date_decimal_to_float).astype("float64")


def load_weather_base(config: dict) -> pd.DataFrame:
    """Lê XLSX, CSV ou Parquet e remove colunas de índice criadas em exportações anteriores."""
    input_path = resolve_input_path(config)
    print(f"Lendo arquivo: {input_path}")

    suffix = input_path.suffix.lower()
    if suffix in {".xlsx", ".xls"}:
        df = pd.read_excel(input_path, engine="openpyxl")
    elif suffix == ".csv":
        # Tenta primeiro separador padrão; se vier uma única coluna, tenta separador brasileiro.
        df = pd.read_csv(input_path)
        if df.shape[1] == 1:
            df = pd.read_csv(input_path, sep=";", decimal=",")
    elif suffix == ".parquet":
        df = pd.read_parquet(input_path)
    else:
        raise ValueError(f"Formato não suportado: {suffix}")

    cols_to_drop = [
        col for col in df.columns
        if str(col).startswith("Unnamed") or str(col).lower() in {"none", "nan"}
    ]
    df = df.drop(columns=cols_to_drop, errors="ignore")

    return df


def has_timezone_suffix(series: pd.Series, sample_size: int = 1000) -> bool:
    """Detecta se amostras textuais têm sufixo de fuso, como Z, -03:00 ou +0000."""
    sample = series.dropna().astype(str).head(sample_size)
    if sample.empty:
        return False
    return sample.str.contains(r"(Z|[+-]\d{2}:?\d{2})$", regex=True).any()


def parse_openmeteo_time(series: pd.Series, target_timezone: str) -> pd.Series:
    """
    Padroniza a coluna temporal.

    - Se houver sufixo de fuso, converte para target_timezone e remove tzinfo.
    - Se não houver fuso, assume que a Open-Meteo já retornou hora local.
    """
    if has_timezone_suffix(series):
        parsed_utc = pd.to_datetime(series, errors="coerce", utc=True)
        return parsed_utc.dt.tz_convert(target_timezone).dt.tz_localize(None)
    parsed = pd.to_datetime(series, errors="coerce")
    try:
        return parsed.dt.tz_localize(None)
    except Exception:
        return parsed


