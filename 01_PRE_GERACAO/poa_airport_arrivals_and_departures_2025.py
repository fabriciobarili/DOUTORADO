import unicodedata
import re

def normalize_columns(name):
    # Tenta corrigir possíveis problemas de codificação (mojibake) vindos do CSV
    try:
        name = name.encode('latin1').decode('utf-8')
    except Exception:
        pass

    # Remove acentuação
    name = unicodedata.normalize('NFKD', name).encode('ASCII', 'ignore').decode('utf-8')

    # Remove caracteres especiais (como parênteses)
    name = re.sub(r'[^\w\s]', '', name)

    # Substitui espaços por subtraço e converte para maiúsculo (ou minúsculo, como preferir)
    name = re.sub(r'\s+', '_', name.strip())

    return name.upper()

