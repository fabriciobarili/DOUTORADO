def validate_openmeteo_schema(df: pd.DataFrame, config: dict) -> pd.DataFrame:
    """Gera relatório compacto de qualidade e coerência das colunas principais."""
    rows = []

    for col in OPEN_METEO_EXPECTED_COLS:
        rows.append({
            "check": "schema_expected_column",
            "column": col,
            "status": "ok" if col in df.columns else "missing",
            "detail": "coluna esperada na base Open-Meteo usada pelo pipeline",
        })

    plausible_ranges = {
        config["temperature_col"]: (-60, 65),
        config["humidity_col"]: (0, 100),
        config["dew_point_col"]: (-80, 40),
        config["apparent_temperature_col"]: (-80, 70),
        config["precipitation_col"]: (0, 300),
        config["rain_col"]: (0, 300),
        config["weather_code_col"]: (0, 99),
        config["pressure_col"]: (850, 1100),
        config["surface_pressure_col"]: (800, 1100),
        config["cloud_cover_col"]: (0, 100),
        config["wind_10m_col"]: (0, 180),
        config["wind_100m_col"]: (0, 220),
    }

    for col, (lo, hi) in plausible_ranges.items():
        if col not in df.columns:
            continue
        s = pd.to_numeric(df[col], errors="coerce")
        rows.append({
            "check": "numeric_quality",
            "column": col,
            "status": "ok" if s.notna().any() else "empty_or_invalid",
            "detail": f"min={s.min()}, max={s.max()}, missing={int(s.isna().sum())}, out_of_range={int(((s < lo) | (s > hi)).sum())}",
        })

    return pd.DataFrame(rows)


def prepare_weather_dataframe(df_raw: pd.DataFrame, config: dict) -> pd.DataFrame:
    """Padroniza tempo, corrige variáveis meteorológicas e cria variáveis auxiliares."""
    df = df_raw.copy()

    time_col = config["time_col"]
    if time_col not in df.columns:
        raise KeyError(f"Coluna temporal '{time_col}' não encontrada na base.")

    df["time_local"] = parse_openmeteo_time(df[time_col], config["target_timezone"])

    numeric_cols = [
        config["temperature_col"],
        config["humidity_col"],
        config["dew_point_col"],
        config["apparent_temperature_col"],
        config["precipitation_col"],
        config["rain_col"],
        config["weather_code_col"],
        config["pressure_col"],
        config["surface_pressure_col"],
        config["cloud_cover_col"],
        config["wind_10m_col"],
        config["wind_100m_col"],
        config["wind_gusts_10m_col"],
        config["shortwave_radiation_col"],
        config["direct_radiation_col"],
        config["is_day_col"],
        config["sunshine_duration_col"],
        "soil_temperature_0_to_7cm",
        "soil_temperature_7_to_28cm",
        "soil_temperature_28_to_100cm",
        "soil_temperature_100_to_255cm",
    ]

    for col in numeric_cols:
        if col in df.columns:
            df[col] = clean_numeric_weather_column(df[col])

    # Limites físicos simples para evitar efeitos de erro de tipo.
    hum = config["humidity_col"]
    cloud = config["cloud_cover_col"]
    wind = config["wind_10m_col"]
    gust = config["wind_gusts_10m_col"]

    if hum in df.columns:
        df[hum] = df[hum].clip(0, 100)
    if cloud in df.columns:
        df[cloud] = df[cloud].clip(0, 100)
    if wind in df.columns:
        df[wind] = df[wind].clip(lower=0)
    if gust in df.columns:
        df[gust] = df[gust].clip(lower=0)

    # Componentes temporais.
    df["date"] = df["time_local"].dt.date
    df["hour"] = df["time_local"].dt.hour
    df["month"] = df["time_local"].dt.month
    df["dayofweek"] = df["time_local"].dt.dayofweek

    # Período prioritário: 06:00 a 20:00.
    start = config["priority_hour_start"]
    end = config["priority_hour_end"]
    df["is_priority_period_06_20"] = df["hour"].between(start, end, inclusive="both")
    df["thermal_time_weight"] = np.where(
        df["is_priority_period_06_20"],
        config["priority_period_weight"],
        config["off_period_weight"],
    )

    # Conversão de vento.
    wind_col = config["wind_10m_col"]
    if wind_col not in df.columns:
        raise KeyError(f"Coluna de vento '{wind_col}' não encontrada.")

    if config["wind_speed_unit"].lower() == "kmh":
        df["wind_speed_10m_kmh"] = df[wind_col]
        df["wind_speed_10m_mps"] = df[wind_col] / 3.6
        if gust in df.columns:
            df["wind_gusts_10m_kmh"] = df[gust]
            df["wind_gusts_10m_mps"] = df[gust] / 3.6
    elif config["wind_speed_unit"].lower() == "mps":
        df["wind_speed_10m_mps"] = df[wind_col]
        df["wind_speed_10m_kmh"] = df[wind_col] * 3.6
        if gust in df.columns:
            df["wind_gusts_10m_mps"] = df[gust]
            df["wind_gusts_10m_kmh"] = df[gust] * 3.6
    else:
        raise ValueError("CONFIG['wind_speed_unit'] deve ser 'kmh' ou 'mps'.")

    if config["use_wind_gusts_if_available"] and "wind_gusts_10m_kmh" in df.columns:
        df["wind_effective_10m_kmh"] = np.maximum(df["wind_speed_10m_kmh"], df["wind_gusts_10m_kmh"])
    else:
        df["wind_effective_10m_kmh"] = df["wind_speed_10m_kmh"]

    # Proxy de temperatura radiante média.
    tdb = config["temperature_col"]
    mrt_method = config["mrt_proxy_method"]
    df["mean_radiant_temperature_proxy"] = df[tdb] + config["mrt_fixed_offset_c"]

    if mrt_method == "cloud_proxy" and config["cloud_cover_col"] in df.columns:
        clear_sky_factor = 1 - (df[config["cloud_cover_col"]] / 100.0)
        daytime_factor = df["is_priority_period_06_20"].astype(float)
        df["mean_radiant_temperature_proxy"] = (
            df[tdb]
            + config["mrt_fixed_offset_c"]
            + daytime_factor * clear_sky_factor * config["mrt_daytime_clear_sky_offset_c"]
        )
    elif mrt_method == "solar_simple" and config["shortwave_radiation_col"] in df.columns:
        solar = df[config["shortwave_radiation_col"]].fillna(0).clip(lower=0)
        solar_offset = (solar / 100.0 * config["mrt_solar_offset_per_100w_m2"]).clip(
            upper=config["mrt_solar_max_offset_c"]
        )
        df["mean_radiant_temperature_proxy"] = df[tdb] + config["mrt_fixed_offset_c"] + solar_offset

    # Rótulo do código meteorológico.
    if config["weather_code_col"] in df.columns:
        df["weather_code_label"] = df[config["weather_code_col"]].map(openmeteo_weather_code_label)

    return df

